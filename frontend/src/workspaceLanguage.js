export function translateWorkspace(language, message, values = {}) {
  if (typeof message !== 'string') return message;
  const output = language === 'bn' && Object.hasOwn(bn, message) ? bn[message] : message;
  return output.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name]) : token);
}

export const WorkspaceLanguage = createContext({
  language: 'en',
  t: message => message,
});

export function useWorkspaceLanguage() {
  return useContext(WorkspaceLanguage);
}
